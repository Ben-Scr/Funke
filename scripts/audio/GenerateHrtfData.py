"""Embed the MIT diffuse-field KEMAR HRIRs without a runtime asset dependency."""

import argparse
import hashlib
import io
from pathlib import Path
import re
import struct
import wave
import zipfile

ARCHIVE_SHA256 = "a48e73137390626ef1e45d1de6a4d98530c6aa570e71b40f7c4442241ed5fa22"


def generate(archive: Path, destination: Path) -> None:
    data = archive.read_bytes()
    if hashlib.sha256(data).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("Expected the original https://sound.media.mit.edu/resources/KEMAR/diffuse.zip")
    measurements = []
    with zipfile.ZipFile(io.BytesIO(data)) as source:
        for name in source.namelist():
            match = re.search(r"H(-?\d+)e(\d+)a\.wav$", name)
            if not match:
                continue
            elevation, azimuth = map(int, match.groups())
            with wave.open(io.BytesIO(source.read(name))) as wav:
                if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getnframes()) != (2, 2, 44100, 128):
                    raise ValueError(f"Unexpected HRIR format: {name}")
                samples = struct.unpack("<256h", wav.readframes(128))
            measurements.append((elevation, azimuth, samples))
    measurements.sort()
    if len(measurements) != 368:
        raise ValueError(f"Expected 368 symmetric measurement pairs, got {len(measurements)}")
    lines = [
        "#pragma once",
        "// Generated by scripts/audio/GenerateHrtfData.py; do not edit.",
        "// KEMAR data: Copyright 1994 MIT Media Laboratory, Bill Gardner and Keith Martin.",
        "// Attribution and terms: External/kemar/LICENSE; source: https://sound.media.mit.edu/resources/KEMAR.html",
        "#include <cstdint>",
        "namespace Funke::KemarData {",
        "struct Measurement { int Elevation; int Azimuth; int16_t Samples[256]; };",
        "inline constexpr Measurement Measurements[] = {",
    ]
    for elevation, azimuth, samples in measurements:
        lines.append(f"\t{{ {elevation}, {azimuth}, {{")
        for i in range(0, len(samples), 16):
            lines.append("\t\t" + ", ".join(map(str, samples[i:i + 16])) + ",")
        lines.append("\t} },")
    lines.extend(["};", "}", ""])
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "Funke-Engine/src/Audio/HrtfKemarData.hpp")
    args = parser.parse_args()
    generate(args.archive, args.output)
