"""Native package layers for players that link everything statically (Android, iOS, Web).

Desktop loads Pkg.<Name>.Native as a DLL. The platform players can't, so the builder compiles each package's
`native` / `native_standalone` layer into the player instead:

    packages = prepare_native_packages(request, out_dir, symbol_table=True)
    cmake ... -DFUNKE_NATIVE_PACKAGES=<packages.json_path>   # read by funke_add_native_packages()

Every package gets its own FunkePackage_OnLoad_<Id> / FunkePackage_OnUnload_<Id> (the CMake function renames
them with -D), and the generated registry source defines FunkeRegisterStaticPackages(), which the player calls
before the engine starts. With `symbol_table` the registry also lists every FUNKE_PACKAGE_API function, so Mono's
P/Invoke override can resolve [DllImport("Pkg.<Name>.Native")] and the linker keeps those functions. The Web
relink builds its own P/Invoke table from the Pkg.<Name>.Native.a archives instead.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from .packages import ProjectPackage, project_packages
from .protocol import BuildRequest, BuilderError, emit_log

_COMPILED_SUFFIXES = {".c", ".cc", ".cpp", ".cxx"}
_LAYERS = (("native", True), ("engine_core", True), ("native_standalone", False), ("standalone_cpp", False))
_EXPORT = re.compile(r"\bFUNKE_PACKAGE_API\b[^;{}()]*?\b([A-Za-z_]\w*)\s*\(")
_COMMENTS = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)
_ENTRY_POINTS = ("FunkePackage_OnLoad", "FunkePackage_OnUnload")


@dataclass
class NativePackage:
    name: str
    version: str
    target: str            # Pkg.<Name>.Native: CMake target, archive name and [DllImport] library name
    id: str                # Name with every non-alphanumeric replaced by "_"
    links_engine: bool
    sources: list[Path]
    includes: list[Path]
    exports: list[str] = field(default_factory=list)
    has_on_unload: bool = False


@dataclass
class NativePackages:
    json_path: Path
    packages: list[NativePackage]

    @property
    def targets(self) -> list[str]:
        return [p.target for p in self.packages]


def _layer(package: ProjectPackage) -> tuple[dict, bool] | None:
    layers = package.manifest.get("layers") or {}
    if not isinstance(layers, dict):
        return None
    for key, links_engine in _LAYERS:
        layer = layers.get(key)
        if isinstance(layer, dict):
            return layer, links_engine
    return None


def _scan_exports(sources: list[Path]) -> tuple[list[str], set[str]]:
    exports: list[str] = []
    entry_points: set[str] = set()
    for source in sources:
        text = _COMMENTS.sub("", source.read_text(encoding="utf-8-sig", errors="replace"))
        for name in _EXPORT.findall(text):
            if name in _ENTRY_POINTS:
                entry_points.add(name)
            elif name not in exports:
                exports.append(name)
    return exports, entry_points


def _native_package(package: ProjectPackage) -> NativePackage | None:
    found = _layer(package)
    if not found:
        return None
    layer, links_engine = found
    files = package.files(layer.get("sources"))
    sources = [f for f in files if f.suffix.lower() in _COMPILED_SUFFIXES]
    if not sources:
        return None
    includes = []
    for entry in [*(layer.get("includes") or []), *(layer.get("private_includes") or [])]:
        directory = package.root / str(entry)
        if directory.is_dir() and directory not in includes:
            includes.append(directory)
    exports, entry_points = _scan_exports(sources)
    if "FunkePackage_OnLoad" not in entry_points:
        raise BuilderError(f"{package.name}: no FUNKE_PACKAGE_API FunkePackage_OnLoad() in its native sources.")
    return NativePackage(
        name=package.name,
        version=str(package.manifest.get("version") or ""),
        target=f"Pkg.{package.name}.Native",
        id=re.sub(r"[^A-Za-z0-9]", "_", package.name),
        links_engine=links_engine,
        sources=sources,
        includes=includes,
        exports=exports,
        has_on_unload="FunkePackage_OnUnload" in entry_points,
    )


def _c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _registry_source(packages: list[NativePackage], symbol_table: bool) -> str:
    lines = [
        "// Generated by the Funke platform builder (funke_platform_sdk/native_packages.py). Do not edit.",
        '#include "Packages/StaticPackages.hpp"',
        "",
        "#include <iterator>",
        "",
    ]
    if packages:
        lines.append('extern "C" {')
        for p in packages:
            lines.append(f"int FunkePackage_OnLoad_{p.id}();")
            if p.has_on_unload:
                lines.append(f"void FunkePackage_OnUnload_{p.id}();")
            if symbol_table:
                # Only the addresses are taken; the real signatures live in the package.
                lines += [f"void {name}();" for name in p.exports]
        lines += ["}", ""]
        tables = [p for p in packages if symbol_table and p.exports]
        if tables:
            lines.append("namespace {")
            for p in tables:
                lines.append(f"\tconst Funke::StaticPackageSymbol k_Symbols_{p.id}[] = {{")
                lines += [f"\t\t{{ {_c_string(name)}, reinterpret_cast<const void*>(&{name}) }}," for name in p.exports]
                lines.append("\t};")
            lines += ["}", ""]
    lines.append('extern "C" void FunkeRegisterStaticPackages() {')
    for p in packages:
        with_symbols = symbol_table and p.exports
        lines += [
            "\t{",
            "\t\tFunke::StaticPackage package;",
            f"\t\tpackage.Name = {_c_string(p.name)};",
            f"\t\tpackage.Version = {_c_string(p.version)};",
            f"\t\tpackage.NativeLibrary = {_c_string(p.target)};",
            f"\t\tpackage.OnLoad = &FunkePackage_OnLoad_{p.id};",
        ]
        if p.has_on_unload:
            lines.append(f"\t\tpackage.OnUnload = &FunkePackage_OnUnload_{p.id};")
        if with_symbols:
            lines += [f"\t\tpackage.Symbols = k_Symbols_{p.id};",
                      f"\t\tpackage.SymbolCount = std::size(k_Symbols_{p.id});"]
        lines += ["\t\tFunke::StaticPackages::Register(package);", "\t}"]
    lines += ["}", ""]
    return "\n".join(lines)


def _write_if_changed(path: Path, text: str) -> None:
    # An unchanged registry must not trigger a relink of the player.
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def prepare_native_packages(request: BuildRequest, out_dir: Path, *, symbol_table: bool) -> NativePackages:
    """Writes <out_dir>/native-packages.json and FunkeStaticPackages.cpp for the game's native package layers."""
    packages = []
    for package in project_packages(request.engine_root, request.project_root, request.content_dir):
        native = _native_package(package)
        if native:
            packages.append(native)
    registry = out_dir / "FunkeStaticPackages.cpp"
    _write_if_changed(registry, _registry_source(packages, symbol_table))
    data = {
        "registry": registry.as_posix(),
        "packages": [{
            "name": p.name,
            "target": p.target,
            "id": p.id,
            "engine": 1 if p.links_engine else 0,
            "sources": [s.as_posix() for s in p.sources],
            "includes": [i.as_posix() for i in p.includes],
        } for p in packages],
    }
    json_path = out_dir / "native-packages.json"
    _write_if_changed(json_path, json.dumps(data, indent=2) + "\n")
    if packages:
        emit_log("Native package layers linked into the player: " + ", ".join(p.name for p in packages))
    return NativePackages(json_path, packages)
