"""Bounded Windows Editor lifecycle attribution; reports measurements, not a leak-free certification."""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import math
import os
from pathlib import Path
import shutil
import subprocess
import threading
import time

REPO = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("memory_bridge", REPO / "scripts/benchmarks/project-open/Run.py")
bridge_support = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bridge_support)


def hide_test_window(process, timeout):
    """Keep the fixture rendering in the background. Minimizing pauses the Editor."""
    import ctypes
    from ctypes import wintypes

    user32 = ctypes.WinDLL("user32", use_last_error=True)
    callback_type = ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)
    user32.EnumWindows.argtypes = [callback_type, wintypes.LPARAM]
    user32.GetWindowThreadProcessId.argtypes = [wintypes.HWND, ctypes.POINTER(wintypes.DWORD)]
    user32.GetClassNameW.argtypes = [wintypes.HWND, wintypes.LPWSTR, ctypes.c_int]
    user32.IsWindowVisible.argtypes = [wintypes.HWND]
    user32.ShowWindowAsync.argtypes = [wintypes.HWND, ctypes.c_int]
    hidden = False
    requested_window = None

    @callback_type
    def visit(window, _):
        nonlocal hidden, requested_window
        pid = wintypes.DWORD()
        user32.GetWindowThreadProcessId(window, ctypes.byref(pid))
        if pid.value == process.pid:
            name = ctypes.create_unicode_buffer(64)
            user32.GetClassNameW(window, name, len(name))
            if name.value == "SDL_app":
                if user32.IsWindowVisible(window):
                    user32.ShowWindowAsync(window, 0)  # SW_HIDE leaves the game loop running.
                    requested_window = window
                elif requested_window == window:
                    hidden = True
                return False
        return True

    deadline = time.monotonic() + min(timeout, 30)
    while process.poll() is None and time.monotonic() < deadline:
        user32.EnumWindows(visit, 0)
        if hidden:
            return
        time.sleep(0.1)
    raise RuntimeError("The test Editor's SDL window could not be hidden")


def run(args):
    root = args.root.resolve()
    root.mkdir(parents=True, exist_ok=False)
    editor = args.editor.resolve()
    fixture = (REPO / "Tests/Fixtures/CSharpScripting/MemoryLifecycle.cs").read_text(encoding="utf-8")
    project = root / "project"
    source = project / "Assets/Scripts/MemoryLifecycle.cs"
    source.parent.mkdir(parents=True)
    source.write_text(fixture, encoding="utf-8")
    scene_dir = project / "Assets/Scenes"
    scene_dir.mkdir(parents=True)
    for name in ("First", "Second"):
        bridge_support.write_json(scene_dir / f"{name}.scene", {
            "version": 1, "name": name, "systems": [{"className": "MemoryLifecycle", "fields": {}}],
            "entities": [{"name": "Camera", "Transform2D": {}, "Camera2D": {"orthoSize": 5}}]})
    bridge_support.write_json(project / "project.json", {
        "projectFormatVersion": 2, "name": "MemoryLifecycle", "engineVersion": "2026.1.0-beta.1",
        "startupScene": "First", "lastOpenedScene": "First", "modules": ["Funke.2D", "Funke.Physics2D"],
        "renderBackend": "Direct3D12", "buildScenes": ["First", "Second"], "buildWidth": 640, "buildHeight": 360})
    # Standard generated-project layout, private to this check.
    (project / "MemoryLifecycle.csproj").write_text('''<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Library</OutputType>
    <Nullable>enable</Nullable><AllowUnsafeBlocks>true</AllowUnsafeBlocks><EnableDynamicLoading>true</EnableDynamicLoading>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems><AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
    <OutputPath>bin/$(Configuration)/</OutputPath></PropertyGroup>
  <ItemGroup><Compile Include="Assets/**/*.cs"/><Reference Include="Funke-ScriptCore"><HintPath>Packages/Funke-ScriptCore/Funke-ScriptCore.dll</HintPath><Private>true</Private></Reference></ItemGroup>
  <Import Project="Packages/FunkeDefines.props" Condition="Exists('Packages/FunkeDefines.props')" />
</Project>''', encoding="utf-8")
    core = project / "Packages/Funke-ScriptCore/Funke-ScriptCore.dll"
    core.parent.mkdir(parents=True)
    shutil.copy2(editor.parent / "Funke-ScriptCore.dll", core)
    (project / "Packages/FunkeDefines.props").write_text(
        '<!-- Auto-generated by the Funke editor on every project save. -->\n'
        '<!-- Edit Project Settings \u2192 Build Settings \u2192 Custom Defines instead. -->\n'
        '<Project>\n  <PropertyGroup>\n'
        '    <DefineConstants>$(DefineConstants);FUNKE_EDITOR;FUNKE_BUILD_DEVELOPMENT;FUNKE_WINDOWS</DefineConstants>\n'
        '  </PropertyGroup>\n</Project>\n', encoding="utf-8", newline="\n")
    bridge_support.write_json(root / "user-data/Funke/Editor/EditorPreferences.json", {
        "AutoRecompileScripts": False, "RecompileScriptsOnPlay": False, "ExitPlayModeOnRecompilation": False})
    env = bridge_support.child_environment() | {
        "FUNKE_USER_DATA_ROOT": str(root / "user-data"), "FUNKE_EDITOR_BRIDGE": "1",
        "FUNKE_MEMORY_UNCAPPED": "1" if args.uncapped else "0",
        "DOTNET_CLI_HOME": str(root / "dotnet-home"), "MSBuildEnableWorkloadResolver": "false",
        "DOTNET_CLI_WORKLOAD_UPDATE_NOTIFY_DISABLE": "true", "DOTNET_CLI_TELEMETRY_OPTOUT": "1"}
    binary_paths = [editor, editor.parent / "Funke-Engine.dll", editor.parent / "Funke-ScriptCore.dll",
                    editor.parent / "Tracy.dll", editor.parent / "ScriptCompiler/Funke-ScriptCompiler.dll"]
    def hashes():
        return {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in binary_paths if p.exists()}
    report = {"status": "running", "mode": args.mode, "requestedCycles": args.cycles, "samples": [],
              "binariesBefore": hashes(), "fixtureSha256": hashlib.sha256(fixture.encode()).hexdigest(),
              "uncapped": args.uncapped, "playSeconds": args.play_seconds, "hiddenWindow": args.hidden_window,
              "collectEvery": args.collect_every,
              "forcedGc": "disabled" if args.collect_every == 0 else "Explicit diagnostic checkpoints only; no engine GC policy changed"}
    process = None
    instance = None
    watchdog = None
    started = time.monotonic()
    def call(command, arguments=None, require_ok=True):
        if time.monotonic() - started > args.timeout:
            raise TimeoutError("Lifecycle check deadline exceeded")
        response = bridge_support.bridge(instance, command, arguments, timeout_ms=30000)
        with (root / "commands.jsonl").open("a", encoding="utf-8") as log:
            log.write(json.dumps({"elapsed": time.monotonic() - started, "command": command,
                                  "args": arguments, "response": response}) + "\n")
        if require_ok and not response.get("ok"):
            raise RuntimeError(str(response))
        return response.get("result", response)
    def snapshot(label, cycle):
        result = call("exec", {"command": "memory.lifecycle.state"})
        if not result.get("ok"):
            raise RuntimeError(str(result))
        sample = json.loads(result["output"])
        sample.update(label=label, cycle=cycle, elapsed=time.monotonic() - started)
        report["samples"].append(sample)
        bridge_support.write_json(root / "report.json", report)
        print(json.dumps(sample), flush=True)
        return sample
    try:
        if args.mode == "steady":
            dotnet_root = Path(os.environ["ProgramFiles"]) / "dotnet"
            sdk = sorted((dotnet_root / "sdk").glob("10.*"))[-1]
            reference_dir = sorted((dotnet_root / "packs/Microsoft.NETCore.App.Ref").glob("10.*"))[-1] / "ref/net10.0"
            target = project / "bin/Release/MemoryLifecycle.dll"
            target.parent.mkdir(parents=True)
            command = [str(dotnet_root / "dotnet.exe"), "exec", str(sdk / "Roslyn/bincore/csc.dll"),
                "-nologo", "-target:library", "-nullable:enable", "-optimize+", "-define:FUNKE_EDITOR,FUNKE_BUILD_DEVELOPMENT,FUNKE_WINDOWS", f"-out:{target}", f"-r:{core}",
                *[f"-r:{p}" for p in reference_dir.glob("*.dll")], str(source)]
            built = subprocess.run(command, env=env, capture_output=True, timeout=30, creationflags=subprocess.CREATE_NO_WINDOW)
            (root / "fixture-build.log").write_bytes(built.stdout + built.stderr)
            if built.returncode:
                raise RuntimeError("Diagnostic fixture compilation failed; see fixture-build.log")
            env.update(FUNKE_EDITOR_AUTOPLAY="1", FUNKE_EDITOR_BRIDGE="0", DOTNET_EnableDiagnostics="0",
                       FUNKE_MEMORY_SAMPLE_OUTPUT=str(root / "samples.jsonl"),
                       FUNKE_MEMORY_UNCAPPED="1" if args.uncapped else "0",
                       FUNKE_MEMORY_COLLECT_INTERVAL=str(args.collect_seconds),
                       FUNKE_MEMORY_SCENE_CYCLES=str(args.scene_cycles))
            report.update(uncapped=args.uncapped, requestedSeconds=args.seconds, forcedGcIntervalSeconds=args.collect_seconds,
                          requestedSceneTransitions=args.scene_cycles,
                          forcedGc="disabled" if args.collect_seconds == 0 else "Diagnostic collections inside the fixture only",
                          fixtureBinarySha256=hashlib.sha256(target.read_bytes()).hexdigest())
            with (root / "process.log").open("wb") as log:
                process = subprocess.Popen([str(editor), f"--project={project}", "--background", "--mute", f"--quit-after={args.seconds}"],
                    cwd=editor.parent, env=env, stdout=log, stderr=subprocess.STDOUT, creationflags=subprocess.CREATE_NO_WINDOW)
            report["pid"] = process.pid
            if args.hidden_window:
                hide_test_window(process, args.timeout)
            bridge_support.write_json(root / "report.json", report)
            process.wait(timeout=min(args.timeout, args.seconds + 30))
            report["exitCode"] = process.returncode
            samples = root / "samples.jsonl"
            if not samples.exists():
                raise RuntimeError("No actual Play-mode samples were produced")
            report["samples"] = [json.loads(line) for line in samples.read_text().splitlines()]
            if process.returncode != 0 or len(report["samples"]) < max(2, args.seconds - 5):
                raise RuntimeError("Editor did not complete the requested Play-mode interval")
            last = report["samples"][-1]
            if last["sceneTransitions"] != args.scene_cycles or last["sceneStarts"] != args.scene_cycles + 1 or last["sceneDestroys"] != args.scene_cycles:
                raise RuntimeError("Scene lifecycle counts do not match requested transitions")
            if last.get("s_SceneSystems") != 1 or last.get("s_SceneSystemAwoken") != 1:
                raise RuntimeError("Scene-system registries did not return to one live instance")
            if hashes() != report["binariesBefore"]:
                raise RuntimeError("Binaries changed during measurement")
            report["status"] = "passed"
            print(json.dumps({"status": "passed", "samples": len(report["samples"]),
                              "first": report["samples"][0], "last": report["samples"][-1]}), flush=True)
            return
        with (root / "process.log").open("wb") as log:
            process = subprocess.Popen([str(editor), f"--project={project}", "--background", "--mute"],
                cwd=editor.parent, env=env, stdout=log, stderr=subprocess.STDOUT, creationflags=subprocess.CREATE_NO_WINDOW)
        report["pid"] = process.pid
        if args.hidden_window:
            hide_test_window(process, args.timeout)
        watchdog = threading.Timer(args.timeout, lambda: process.kill() if process.poll() is None else None)
        watchdog.daemon = True
        watchdog.start()
        bridge_support.write_json(root / "report.json", report)
        discovery = root / f"user-data/Funke/EditorBridge/{process.pid}.json"
        deadline = time.monotonic() + 90
        while time.monotonic() < deadline:
            if process.poll() is not None:
                raise RuntimeError(f"Editor exited during startup: {process.returncode}")
            instance = bridge_support.read_json(discovery)
            if instance:
                status = call("status")
                if status.get("state") == "edit" and status.get("scene") and not status.get("busy") and not status["scripts"]["compiling"]:
                    break
            time.sleep(.1)
        else:
            raise TimeoutError("Editor did not become ready")
        compilation = call("recompile")
        if not compilation.get("succeeded"):
            raise RuntimeError(str(compilation))
        call("play", {"frames": 8, "size": "640x360", "fixedStep": "60"})
        snapshot("warmup-playing", 0)
        call("stop")
        if args.collect_every > 0:
            call("exec", {"command": "memory.lifecycle.collect"})
        snapshot("baseline-post-gc" if args.collect_every > 0 else "baseline", 0)
        for cycle in range(1, args.cycles + 1):
            if args.mode in ("play", "mixed"):
                play_args = {"seconds": args.play_seconds, "size": "640x360"} if args.play_seconds > 0 else {
                    "frames": args.frames, "size": "640x360", "fixedStep": "60"}
                call("play", play_args)
                state = snapshot("playing", cycle)
                if state["frames"] < (1 if args.play_seconds > 0 else args.frames):
                    raise RuntimeError("Script did not execute requested frames")
                status = call("stop")
                if status["state"] != "edit" or status["entityCount"] != 1:
                    raise RuntimeError("Stop did not restore scene")
                snapshot("stopped", cycle)
            if args.mode == "scene":
                call("open-scene", {"scene": str(scene_dir / ("Second.scene" if cycle % 2 else "First.scene"))})
            if args.mode in ("reload", "mixed"):
                revision = cycle + 1
                source.write_text(fixture.replace("Revision = 1;", f"Revision = {revision};"), encoding="utf-8")
                compilation = call("recompile")
                if not compilation.get("succeeded"):
                    raise RuntimeError(str(compilation))
            state = snapshot("after-cycle", cycle)
            if args.mode in ("reload", "mixed") and state["revision"] != cycle + 1:
                raise RuntimeError("Reload left stale code")
            if args.collect_every > 0 and (cycle % args.collect_every == 0 or cycle == args.cycles):
                call("exec", {"command": "memory.lifecycle.collect"})
                snapshot("post-gc", cycle)
        call("shutdown", {"pid": process.pid})
        process.wait(timeout=30)
        report["exitCode"] = process.returncode
        if process.returncode != 0:
            raise RuntimeError(f"Editor exit {process.returncode}")
        if hashes() != report["binariesBefore"]:
            raise RuntimeError("Binaries changed during measurement")
        report["status"] = "passed"
    except BaseException as error:
        report.update(status="failed", error=str(error))
        raise
    finally:
        if watchdog is not None:
            watchdog.cancel()
        if process is not None and process.poll() is None:
            process.terminate()
            process.wait(timeout=15)
        report["wallSeconds"] = time.monotonic() - started
        report["binariesAfter"] = hashes()
        bridge_support.write_json(root / "report.json", report)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--editor", type=Path, required=True)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--mode", choices=("play", "reload", "mixed", "scene", "steady"), required=True)
    parser.add_argument("--cycles", type=int, default=24)
    parser.add_argument("--frames", type=int, default=8)
    parser.add_argument("--play-seconds", type=float, default=0,
                        help="Unscaled Play-time interval instead of fixed-step frame count (0 disables, maximum 25 seconds)")
    parser.add_argument("--collect-every", type=int, default=8,
                        help="Bridge-mode collection cadence; 0 disables all explicit collections including warmup")
    parser.add_argument("--timeout", type=int, default=300)
    parser.add_argument("--seconds", type=int, default=30)
    parser.add_argument("--uncapped", action="store_true")
    parser.add_argument("--hidden-window", action="store_true",
                        help="Hide the Windows test Editor so desktop minimization does not pause a long run")
    parser.add_argument("--collect-seconds", type=int, default=0)
    parser.add_argument("--scene-cycles", type=int, default=0)
    arguments = parser.parse_args()
    if arguments.cycles < 1 or arguments.frames < 1 or arguments.collect_every < 0:
        parser.error("Cycle/frame counts must be positive; collection cadence must be nonnegative")
    if not math.isfinite(arguments.play_seconds) or not 0 <= arguments.play_seconds <= 25:
        parser.error("Play seconds must be between 0 and 25 (within the bridge command timeout)")
    if arguments.seconds < 5 or arguments.collect_seconds < 0 or arguments.timeout < 1:
        parser.error("At least five seconds, nonnegative collection interval and positive timeout are required")
    if arguments.scene_cycles < 0 or arguments.scene_cycles > arguments.seconds - 5:
        parser.error("Scene transitions must leave at least five seconds of steady observation")
    run(arguments)
