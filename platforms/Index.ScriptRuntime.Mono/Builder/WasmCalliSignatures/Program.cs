// Lists every unmanaged function-pointer signature in the given assemblies and writes one placeholder
// [DllImport] per distinct signature.
//
// The Mono interpreter on WebAssembly can only cross between managed and native code through trampolines
// generated at build time, and the .NET SDK generates them only for signatures it sees on [DllImport]s.
// Index-ScriptCore talks to the engine through function pointers in both directions (`calli` through
// `delegate* unmanaged<...>` and [UnmanagedCallersOnly] callbacks), so without these placeholders those
// calls fail at runtime. The placeholder module is never loaded; only the signatures matter.
//
// Collected: every `calli` with an unmanaged calling convention, every `delegate* unmanaged` type in a
// field, method signature or local, and every [UnmanagedCallersOnly] method.
//
// Usage: WasmCalliSignatures <output.cs> <assembly.dll>...

using System.Collections.Immutable;
using System.Reflection;
using System.Reflection.Emit;
using System.Reflection.Metadata;
using System.Reflection.Metadata.Ecma335;
using System.Reflection.PortableExecutable;
using System.Text;

if (args.Length < 1)
{
    Console.Error.WriteLine("usage: WasmCalliSignatures <output.cs> <assembly.dll>...");
    return 2;
}

var operandTypes = typeof(OpCodes).GetFields(BindingFlags.Public | BindingFlags.Static)
    .Select(f => (OpCode)f.GetValue(null)!)
    .ToDictionary(op => (ushort)op.Value, op => op.OperandType);

var provider = new SignatureTypes();
foreach (string path in args.Skip(1))
{
    using var stream = File.OpenRead(path);
    using var pe = new PEReader(stream);
    if (!pe.HasMetadata) continue;
    MetadataReader metadata = pe.GetMetadataReader();
    provider.CurrentAssembly = Path.GetFileName(path);
    var decoder = new SignatureDecoder<string, object?>(provider, metadata, null);

    foreach (FieldDefinitionHandle handle in metadata.FieldDefinitions)
    {
        BlobReader blob = metadata.GetBlobReader(metadata.GetFieldDefinition(handle).Signature);
        decoder.DecodeFieldSignature(ref blob);
    }

    foreach (MethodDefinitionHandle handle in metadata.MethodDefinitions)
    {
        MethodDefinition method = metadata.GetMethodDefinition(handle);
        BlobReader methodBlob = metadata.GetBlobReader(method.Signature);
        MethodSignature<string> methodSignature = decoder.DecodeMethodSignature(ref methodBlob);
        if (IsUnmanagedCallersOnly(metadata, method)) provider.Record(methodSignature);

        if (method.RelativeVirtualAddress == 0) continue;
        MethodBodyBlock body = pe.GetMethodBody(method.RelativeVirtualAddress);
        if (!body.LocalSignature.IsNil)
        {
            BlobReader locals = metadata.GetBlobReader(metadata.GetStandaloneSignature(body.LocalSignature).Signature);
            decoder.DecodeLocalSignature(ref locals);
        }

        BlobReader il = body.GetILReader();
        while (il.RemainingBytes > 0)
        {
            ushort code = il.ReadByte();
            if (code == 0xFE) code = (ushort)(0xFE00 | il.ReadByte());
            if (!operandTypes.TryGetValue(code, out OperandType operand))
            {
                Console.Error.WriteLine($"warning: unknown IL opcode 0x{code:X} in {path}; skipping the rest of a method.");
                break;
            }
            if (code == (ushort)ILOpCode.Calli)
            {
                var signatureHandle = (StandaloneSignatureHandle)MetadataTokens.Handle(il.ReadInt32());
                BlobReader blob = metadata.GetBlobReader(metadata.GetStandaloneSignature(signatureHandle).Signature);
                MethodSignature<string> signature = decoder.DecodeMethodSignature(ref blob);
                if (IsUnmanaged(signature.Header)) provider.Record(signature);
                continue;
            }
            // Computed before touching Offset: InlineSwitch reads its target count first.
            int skip = operand switch
            {
                OperandType.InlineNone => 0,
                OperandType.ShortInlineBrTarget or OperandType.ShortInlineI or OperandType.ShortInlineVar => 1,
                OperandType.InlineVar => 2,
                OperandType.InlineI8 or OperandType.InlineR => 8,
                OperandType.InlineSwitch => 4 * il.ReadInt32(),
                _ => 4,
            };
            il.Offset += skip;
        }
    }
}

var source = new StringBuilder();
source.AppendLine("// <auto-generated> by Index.ScriptRuntime.Mono/Builder/WasmCalliSignatures. Do not edit. </auto-generated>");
source.AppendLine("using System.Runtime.InteropServices;");
source.AppendLine();
source.AppendLine("internal static class IndexWasmCalliSignatures");
source.AppendLine("{");
int index = 0;
foreach (string signature in provider.Signatures)
{
    int open = signature.IndexOf('(');
    string returnType = signature[..open];
    string[] parameters = signature[(open + 1)..^1].Split(',', StringSplitOptions.RemoveEmptyEntries);
    string parameterList = string.Join(", ", parameters.Select((type, i) => $"{type} p{i}"));
    source.AppendLine($"    [DllImport(\"IndexWebCalliSignatures\")] private static extern {returnType} S{index++}({parameterList});");
}
source.AppendLine("}");
File.WriteAllText(args[0], source.ToString());
Console.WriteLine($"{provider.Signatures.Count} unmanaged function-pointer signature(s)");
return 0;

static bool IsUnmanaged(SignatureHeader header)
    => header.CallingConvention is not (SignatureCallingConvention.Default or SignatureCallingConvention.VarArgs);

static bool IsUnmanagedCallersOnly(MetadataReader metadata, MethodDefinition method)
{
    foreach (CustomAttributeHandle handle in method.GetCustomAttributes())
    {
        CustomAttribute attribute = metadata.GetCustomAttribute(handle);
        EntityHandle type = attribute.Constructor.Kind switch
        {
            HandleKind.MemberReference => metadata.GetMemberReference((MemberReferenceHandle)attribute.Constructor).Parent,
            HandleKind.MethodDefinition => metadata.GetMethodDefinition((MethodDefinitionHandle)attribute.Constructor).GetDeclaringType(),
            _ => default,
        };
        string? name = type.Kind switch
        {
            HandleKind.TypeReference => metadata.GetString(metadata.GetTypeReference((TypeReferenceHandle)type).Name),
            HandleKind.TypeDefinition => metadata.GetString(metadata.GetTypeDefinition((TypeDefinitionHandle)type).Name),
            _ => null,
        };
        if (name == "UnmanagedCallersOnlyAttribute") return true;
    }
    return false;
}

// Maps signature types onto what WebAssembly passes: i32, i64, f32, f64. "?" marks types that would need
// their real definition (structs by value). Unmanaged function-pointer types are recorded on the way.
sealed class SignatureTypes : ISignatureTypeProvider<string, object?>
{
    public SortedSet<string> Signatures { get; } = new(StringComparer.Ordinal);
    public string CurrentAssembly { get; set; } = "";

    public void Record(MethodSignature<string> signature)
    {
        if (signature.ReturnType.Contains('?') || signature.ParameterTypes.Any(t => t.Contains('?')))
        {
            Console.Error.WriteLine($"warning: {CurrentAssembly}: struct-by-value across the native boundary is not supported on Web.");
            return;
        }
        Signatures.Add(signature.ReturnType + "(" + string.Join(",", signature.ParameterTypes) + ")");
    }

    public string GetFunctionPointerType(MethodSignature<string> signature)
    {
        if (signature.Header.CallingConvention is not (SignatureCallingConvention.Default or SignatureCallingConvention.VarArgs))
            Record(signature);
        return "nint";
    }

    public string GetPrimitiveType(PrimitiveTypeCode typeCode) => typeCode switch
    {
        PrimitiveTypeCode.Void => "void",
        PrimitiveTypeCode.Int64 or PrimitiveTypeCode.UInt64 => "long",
        PrimitiveTypeCode.Single => "float",
        PrimitiveTypeCode.Double => "double",
        PrimitiveTypeCode.IntPtr or PrimitiveTypeCode.UIntPtr or PrimitiveTypeCode.String or PrimitiveTypeCode.Object
            or PrimitiveTypeCode.TypedReference => "nint",
        _ => "int",
    };

    public string GetPointerType(string elementType) => "nint";
    public string GetByReferenceType(string elementType) => "nint";
    public string GetSZArrayType(string elementType) => "nint";
    public string GetArrayType(string elementType, ArrayShape shape) => "nint";
    public string GetPinnedType(string elementType) => elementType;
    public string GetModifiedType(string modifier, string unmodifiedType, bool isRequired) => unmodifiedType;
    public string GetGenericInstantiation(string genericType, ImmutableArray<string> typeArguments) => genericType;
    public string GetGenericMethodParameter(object? genericContext, int index) => "?";
    public string GetGenericTypeParameter(object? genericContext, int index) => "?";

    public string GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte rawTypeKind)
        => rawTypeKind == (byte)SignatureTypeKind.ValueType ? EnumOrStruct(reader, reader.GetTypeDefinition(handle)) : "nint";

    public string GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte rawTypeKind)
        => rawTypeKind == (byte)SignatureTypeKind.ValueType ? "?" : "nint";

    public string GetTypeFromSpecification(MetadataReader reader, object? genericContext, TypeSpecificationHandle handle, byte rawTypeKind)
        => rawTypeKind == (byte)SignatureTypeKind.ValueType ? "?" : "nint";

    // Enums travel as their underlying integer; anything else by value is a struct.
    static string EnumOrStruct(MetadataReader reader, TypeDefinition type)
    {
        if (type.BaseType.Kind != HandleKind.TypeReference) return "?";
        TypeReference baseType = reader.GetTypeReference((TypeReferenceHandle)type.BaseType);
        if (reader.GetString(baseType.Name) != "Enum" || reader.GetString(baseType.Namespace) != "System") return "?";
        foreach (FieldDefinitionHandle fieldHandle in type.GetFields())
        {
            FieldDefinition field = reader.GetFieldDefinition(fieldHandle);
            if ((field.Attributes & FieldAttributes.Static) != 0) continue;
            BlobReader blob = reader.GetBlobReader(field.Signature);
            blob.ReadSignatureHeader();
            SignatureTypeCode code = blob.ReadSignatureTypeCode();
            return code is SignatureTypeCode.Int64 or SignatureTypeCode.UInt64 ? "long" : "int";
        }
        return "int";
    }
}
