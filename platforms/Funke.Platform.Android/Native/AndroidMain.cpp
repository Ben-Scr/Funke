// Android entry point: unpacks the game payload from the APK, points the engine and Mono at it,
// then runs the normal Funke runtime.
//
// APK assets are not files, while the engine and Mono expect a directory tree. The builder lists
// every payload file in assets/funke-payload.txt (first line: payload hash); on first launch, or
// after an update, they are copied to internal storage.

#include <SDL3/SDL.h>
#include <SDL3/SDL_main.h>

#include "MonoScriptRuntime.hpp"
#include "Packages/StaticPackages.hpp"
#include "Serialization/Path.hpp"

#include <android/log.h>

#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

int FunkeRuntimeMain(int argc, char** argv);
// Generated by the builder: the game packages' native layers linked into libmain.so.
extern "C" void FunkeRegisterStaticPackages();

namespace {
	constexpr const char* k_Tag = "Funke";

	// [DllImport("Pkg.<Name>.Native")] targets live in libmain.so; anything else falls back to dlopen.
	const void* ResolveStaticPInvoke(const char* libraryName, const char* entryPoint) {
		return Funke::StaticPackages::FindSymbol(libraryName, entryPoint);
	}

	void LogError(const std::string& message) {
		__android_log_write(ANDROID_LOG_ERROR, k_Tag, message.c_str());
	}

	bool ReadAsset(const std::string& name, std::string& out) {
		size_t size = 0;
		void* data = SDL_LoadFile(name.c_str(), &size);
		if (!data) return false;
		out.assign(static_cast<const char*>(data), size);
		SDL_free(data);
		return true;
	}

	bool ExtractPayload(const std::filesystem::path& payloadDir) {
		std::string manifest;
		if (!ReadAsset("funke-payload.txt", manifest)) {
			LogError(std::string("funke-payload.txt missing from the APK: ") + SDL_GetError());
			return false;
		}
		std::istringstream lines(manifest);
		std::string hash;
		std::getline(lines, hash);

		const std::filesystem::path hashFile = payloadDir / ".payload-hash";
		std::string installedHash;
		if (std::ifstream in(hashFile); in) std::getline(in, installedHash);
		if (!hash.empty() && hash == installedHash) return true;

		std::error_code ec;
		std::filesystem::remove_all(payloadDir, ec);
		std::filesystem::create_directories(payloadDir, ec);

		std::string relative;
		std::string bytes;
		while (std::getline(lines, relative)) {
			if (!relative.empty() && relative.back() == '\r') relative.pop_back();
			if (relative.empty()) continue;
			if (!ReadAsset("payload/" + relative, bytes)) {
				LogError("Missing payload asset: " + relative);
				return false;
			}
			const std::filesystem::path target = payloadDir / relative;
			std::filesystem::create_directories(target.parent_path(), ec);
			std::ofstream out(target, std::ios::binary | std::ios::trunc);
			out.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
			if (!out) {
				LogError("Could not write " + target.string());
				return false;
			}
		}
		std::ofstream(hashFile) << hash;
		return true;
	}
}

int main(int argc, char** argv) {
	const char* internal = SDL_GetAndroidInternalStoragePath();
	if (!internal) {
		LogError(std::string("No internal storage path: ") + SDL_GetError());
		return 1;
	}
	const std::filesystem::path payloadDir = std::filesystem::path(internal) / "funke-payload";
	if (!ExtractPayload(payloadDir)) return 1;

	Funke::Path::SetExecutableDirOverride((payloadDir / "game").string());
	// .NET has no LocalApplicationData folder on Android; Application.PersistentDataPath falls back to
	// $HOME, which must be the app's private storage rather than the unwritable default.
	setenv("HOME", internal, 1);

	FunkeRegisterStaticPackages();

	FunkeMonoConfig mono;
	mono.AssembliesDir = (payloadDir / "managed").string();
	mono.RuntimeIdentifier = "android-arm64";
	mono.PInvokeResolver = &ResolveStaticPInvoke;
	FunkeScriptRuntimeMono_Register(mono);

	std::vector<char*> args(argv, argv + argc);
	if (args.empty()) {
		static char name[] = "FunkeGame";
		args.push_back(name);
	}
	return FunkeRuntimeMain(static_cast<int>(args.size()), args.data());
}
